fn width_from_table(table: &[u16; 256], code: u8) -> Option<f64> {
    let width = table[usize::from(code)];
    (width != u16::MAX).then_some(f64::from(width))
}

pub(super) fn helvetica_width(code: u8, bold: bool, oblique: bool) -> Option<f64> {
    let table = match (bold, oblique) {
        (false, false) => &HELVETICA_REGULAR,
        (true, false) => &HELVETICA_BOLD,
        (false, true) => &HELVETICA_OBLIQUE,
        (true, true) => &HELVETICA_BOLD_OBLIQUE,
    };
    width_from_table(table, code)
}

pub(super) fn times_width(code: u8, bold: bool, italic: bool) -> Option<f64> {
    let table = match (bold, italic) {
        (false, false) => &TIMES_ROMAN,
        (true, false) => &TIMES_BOLD,
        (false, true) => &TIMES_ITALIC,
        (true, true) => &TIMES_BOLD_ITALIC,
    };
    width_from_table(table, code)
}

#[cfg(test)]
mod tests {
    use super::{
        HELVETICA_BOLD, HELVETICA_BOLD_OBLIQUE, HELVETICA_OBLIQUE, HELVETICA_REGULAR, TIMES_BOLD,
        TIMES_BOLD_ITALIC, TIMES_ITALIC, TIMES_ROMAN,
    };

    #[test]
    fn helvetica_standard_encoding_tables_cover_expected_glyphs() {
        for table in [
            &HELVETICA_REGULAR,
            &HELVETICA_BOLD,
            &HELVETICA_OBLIQUE,
            &HELVETICA_BOLD_OBLIQUE,
        ] {
            assert_eq!(
                table.iter().filter(|width| **width != u16::MAX).count(),
                149
            );
        }
        assert_eq!(HELVETICA_REGULAR[32], 278);
        assert_eq!(HELVETICA_REGULAR[65], 667);
        assert_eq!(HELVETICA_BOLD[65], 722);
        assert_eq!(HELVETICA_OBLIQUE[174], 500);
        assert_eq!(HELVETICA_BOLD_OBLIQUE[174], 611);
    }

    #[test]
    fn times_standard_encoding_tables_cover_expected_glyphs() {
        for table in [&TIMES_ROMAN, &TIMES_BOLD, &TIMES_ITALIC, &TIMES_BOLD_ITALIC] {
            assert_eq!(
                table.iter().filter(|width| **width != u16::MAX).count(),
                149
            );
        }
        assert_eq!(TIMES_ROMAN[32], 250);
        assert_eq!(TIMES_ROMAN[65], 722);
        assert_eq!(TIMES_BOLD[65], 722);
        assert_eq!(TIMES_ITALIC[65], 611);
        assert_eq!(TIMES_BOLD_ITALIC[65], 667);
        assert_eq!(TIMES_ITALIC[174], 500);
    }
}
